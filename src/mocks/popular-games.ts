export const popularGames: Game[] = list.map(([name, appId, genre, developer], i) => ({
  id: `steam-${appId}`, name, appId, installed: false, configStatus: "none",
  lastModified: new Date(Date.UTC(2026, 0, 1) - i * 36e5).toISOString(),
  installPath: "—", sizeGb: 0, genre, hue: (appId * 37) % 360, favorite: false, developer,
}));

/** Adds popular games that aren't already in the library (matched by Steam App ID). */
export function withPopularGames(games: Game[]): Game[] {
  const have = new Set(games.map((g) => g.appId));
  return [...games, ...popularGames.filter((g) => !have.has(g.appId))];
}
